import os, yaml, json, torch
import pandas as pd
from dataclasses import dataclass, field
from typing import List, Dict, Tuple, Set

@dataclass
class Config:
    # --- Experiment and training settings ---
    START_DATE: str
    END_DATE:str
    TRAIN_END_DATE: str
    TEST_START_DATE: str 
    SEQ_LEN: int
    T_LEN: int
    LEARNING_RATE: float
    FINETUNE_LR: float
    BATCH_SIZE: int
    EPOCHS: int
    OUTPUT_CHANNELS: int
    
    # --- Advanced experiment controls ---
    SEED: int
    TRAIN_VAL_SPLIT: float
    EARLY_STOPPING_TOLERANCE: int
    LATE_FUSION: bool
    TARGET_TIME: str
    INFERENCE_LIMIT_DATE: str
    ROLLING_DAYS: int
    INTERPOLATION_METHOD: str
    GEO_AREA: List[Tuple[float, float]]
    RESOLU: float
    FILL_VALUE: float
    
    # --- File name variable ---
    GEMS:str
    ERA5:str
    GT:str
    STATIC:str
    STD:str
    
    # --- Weights ---
    WEIGHT_DICT: Dict[str, str]

    # --- Characteristics and domain definitions ---
    TARGETFEATURES: List[str]
    EXCLUDE_SET: Set[str]
    GEMS_ABBRE: List[str]
    ERA5_ABBRE: List[str]
    STATIC_ABBRE: List[str]
    TIME_FEATURE: List[str]
    POSITION_FEATURE: List[str]
    POLLUTANT_DOMAINS: Dict[str, Tuple[float, float]]
    
    GEMS_FEATURE: Dict[str, List[str]]
    ERA5_FEATURE: List[str]
    ABBRE_TRANS: Dict[str, str]
    GEMS_QUALITY_FLAGS: Dict[str, int]
    
   # --- Original data path ---
    GEMS_DATA: str
    GEMS_DATA_2025: str
    ERA5_ROOT_PATH: str

    # --- Grid Search ---
    GRID_SEARCH: Dict[str, list] = field(default_factory=dict)

    # ================= Dynamically calculated variables (generated by __post_init__) =================
    ROOT_DIR: str = field(init=False)
    DATA_DIR: str = field(init=False)
    GEMS_PATH: str = field(init=False)
    ERA5_PATH: str = field(init=False)
    GT_PATH: str = field(init=False)
    STATIC_PATH: str = field(init=False)
    STD_PATH: str = field(init=False)
    WEIGHTS_DIR: str = field(init=False)
    FEATURES: List[str] = field(init=False)
    INPUT_CHANNELS: int = field(init=False)
    DEVICE: torch.device = field(init=False)

    def __post_init__(self):
        # 1. Automatic path stitching
        self.ROOT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        self.DATA_DIR = os.path.join(self.ROOT_DIR, "dataset_storage", "processed")
        self.WEIGHTS_DIR = os.path.join(self.ROOT_DIR, "weights")
        
        self.GEMS_PATH = os.path.join(self.DATA_DIR, self.GEMS)
        self.ERA5_PATH = os.path.join(self.DATA_DIR, self.ERA5)
        self.GT_PATH = os.path.join(self.DATA_DIR, self.GT)
        self.STATIC_PATH = os.path.join(self.DATA_DIR, self.STATIC)
        self.STD_PATH = os.path.join(self.DATA_DIR, self.STD)
        
        # 2. Automatically filter features and calculate the number of Channels
        all_features = self.GEMS_ABBRE + self.ERA5_ABBRE + self.TIME_FEATURE + self.POSITION_FEATURE + self.TARGETFEATURES
        all_features.extend(self.STATIC_ABBRE)
        self.FEATURES = [f for f in all_features if f not in self.EXCLUDE_SET]
        self.INPUT_CHANNELS = len(self.FEATURES)
        
        # 3. Determine Device
        self.DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    def to_device(self, data):
        if isinstance(data, list):
            return [x.to(self.DEVICE, non_blocking=True) for x in data]
        elif isinstance(data, torch.Tensor):
            return data.to(self.DEVICE, non_blocking=True)
        return data

    def save_experiment_config(self, save_path: str):
        """ Save core experiment hyperparameters and settings to JSON for reproducibility. """
        export_data = {
            "experiment": {
                "start_date": self.START_DATE,
                "end_date": self.END_DATE,
                "lookback_window": self.SEQ_LEN,
                "predict_step": self.T_LEN,
                "geo_area": self.GEO_AREA,
                "spatial_resolution": self.RESOLU,
                "interpolation_method": self.INTERPOLATION_METHOD,
                "rolling_days": self.ROLLING_DAYS,
                "train_end_date": self.TRAIN_END_DATE,
                "test_start_date": self.TEST_START_DATE,
                "early_stopping_tolerance": self.EARLY_STOPPING_TOLERANCE,
                "seed": self.SEED,
                "late_fusion": self.LATE_FUSION,
                "missing_value_filling": self.FILL_VALUE,
            },
            "hyperparameters": {
                "learning_rate": self.LEARNING_RATE,
                "fine_tune_learning_rate": self.FINETUNE_LR,
                "batch_size": self.BATCH_SIZE,
                "epochs": self.EPOCHS,
                "input_channels": self.INPUT_CHANNELS,
                "output_channels": self.OUTPUT_CHANNELS
            },
            "features": {
                "exclude_set": list(self.EXCLUDE_SET), # Convert Set to List for JSON serialization
                "used_features": self.FEATURES,
                "targets": self.TARGETFEATURES
            }
        }
        with open(save_path, 'w', encoding='utf-8') as f:
            json.dump(export_data, f, indent=4, ensure_ascii=False)

def load_config(yaml_path: str = None) -> Config:
    if yaml_path is None:
        yaml_path = os.path.join(os.path.dirname(__file__), "config.yaml")
        
    with open(yaml_path, 'r', encoding='utf-8') as f:
        raw = yaml.safe_load(f)
        
    # Flatten nested dictionaries from YAML into a single params dictionary for easier access.
    params = {}
    params.update(raw.get('experiment', {}))
    params.update(raw.get('hyperparameters', {}))
    paths_data = raw.get('paths', {})
    params.update(paths_data.get('processed_files', {}))
    params.update(paths_data.get('raw_data', {}))
    params.update(raw.get('features', {}))
    
    return Config(
        # --- Experiment and training settings ---
        START_DATE=pd.to_datetime(str(params['start_date'])).strftime("%Y%m%d"),
        END_DATE=pd.to_datetime(str(params['end_date'])).strftime("%Y%m%d"),
        TRAIN_END_DATE=pd.to_datetime(str(params['train_end_date'])).strftime("%Y%m%d"),
        TEST_START_DATE=pd.to_datetime(str(params['test_start_date'])).strftime("%Y%m%d"),
        SEQ_LEN=int(params['lookback_window']),
        T_LEN=int(params.get('predict_step', 1)),
        LEARNING_RATE=float(params['learning_rate']),
        FINETUNE_LR=float(params['fine_tune_learning_rate']),
        BATCH_SIZE=int(params['batch_size']),
        EPOCHS=int(params['epochs']),
        OUTPUT_CHANNELS=int(params.get('output_channels', 6)),
        
        # --- Advanced experiment controls ---
        SEED=int(params.get('seed', 42)),
        TRAIN_VAL_SPLIT=float(params.get('train_val_split', 0.9)),
        EARLY_STOPPING_TOLERANCE=int(params.get('early_stopping_tolerance', 15)),
        LATE_FUSION=bool(params.get('late_fusion', True)),
        TARGET_TIME=pd.to_datetime(str(params.get('target_time', "202512030400"))).strftime("%Y%m%d%H%M"),
        INFERENCE_LIMIT_DATE=pd.to_datetime(str(params.get('inference_limit_date', "202502010000"))).strftime("%Y%m%d%H%M"),
        ROLLING_DAYS=int(params.get('rolling_days', 3)),
        INTERPOLATION_METHOD=str(params.get('interpolation_method', 'bilinear')),
        GEO_AREA=[tuple(area) for area in params.get('geo_area', [[120.0, 122.0], [21.5, 25.5]])],
        RESOLU=params.get('spatial_resolution', 0.005),
        FILL_VALUE=params.get('missing_value', 0.0),
        
        # --- File name variables ---
        GEMS=params['gems'],
        ERA5=params['era5'],
        GT=params['gt'],
        STATIC=params['static'],
        STD=params['std'],
        
        # --- Weights ---
        WEIGHT_DICT=paths_data.get('weights', {}),
        
        # --- Characteristics and domain definitions ---
        TARGETFEATURES=params['targets'],
        EXCLUDE_SET=set(params['exclude']),
        GEMS_ABBRE=params['gems_abbre'],
        ERA5_ABBRE=params['era5_abbre'],
        STATIC_ABBRE=params['static_abbre'],
        TIME_FEATURE=params['time_embed'],
        POSITION_FEATURE=params['position_embed'],
        POLLUTANT_DOMAINS={k: tuple(v) for k, v in raw['domains']['pollutants'].items()},
        GEMS_FEATURE=params['gems_feature'],
        ERA5_FEATURE=params['era5_feature'],
        ABBRE_TRANS=params['abbre_trans'],
        GEMS_QUALITY_FLAGS={k: int(v, 2) for k, v in raw['features']['gems_quality_flags'].items()},
        
        # --- Original data path ---
        GEMS_DATA=params['gems_dir'],
        GEMS_DATA_2025=params['gems_2025_dir'],
        ERA5_ROOT_PATH=params['era5_dir'],
        
        # --- Grid Search ---
        GRID_SEARCH=raw.get('grid_search') or {}
    )

# Instantiate global setting objects for direct import by other modules in the project.
cfg = load_config()